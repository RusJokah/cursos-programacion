let condicion = true;

if (condicion) {
    console.log("La condición es verdadera.");
} else {
    console.log("La condición es falsa.");
}

// Ejemplo con número
let numero = 7;

if (numero == 1) {
    console.log("El número es uno.");
}
else if (numero == 5) {
    console.log("El número es cinco.");
}
else if (numero == 7) {
    console.log("El número es siete.");
}
else {
    console.log("El número es desconocido.");
}